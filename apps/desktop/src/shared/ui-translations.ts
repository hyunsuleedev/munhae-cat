let patterns: Array<{ pattern: RegExp; indexes: string[]; translation: string }> | undefined;
export function translateUi(text: string, language: UiLanguage): string {
  if (language !== "en") return text;
  const trimmed = text.trim();
  const translated = EN[trimmed];
  if (translated !== undefined) return text.replace(trimmed, () => translated);
  if (!/[가-힣]/.test(text)) return text;
  patterns ??= Object.entries(EN).filter(([key]) => key.includes("{{"))
    .sort(([a], [b]) => b.length - a.length).map(([key, translation]) => {
      const indexes: string[] = [];
      const escaped = key.split(/(\{\{\d+\}\})/).map(part => {
        const match = /^\{\{(\d+)\}\}$/.exec(part);
        if (match) { indexes.push(match[1]!); return "([\\s\\S]*?)"; }
        return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      }).join("");
      return { pattern: new RegExp(`^${escaped}$`), indexes, translation };
    });
  for (const entry of patterns) {
    const match = entry.pattern.exec(trimmed);
    if (!match) continue;
    const values = new Map(entry.indexes.map((index, i) => [index, match[i + 1]!]));
    return text.replace(trimmed, () => entry.translation.replace(/\{\{(\d+)\}\}/g, (_, index: string) => values.get(index) ?? ""));
  }
  return text;
}
