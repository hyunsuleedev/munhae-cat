import { DatabaseSync } from "node:sqlite";
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Build only an in-memory database. The checked-in SQL migrations remain the
// authority for DDL, indexes, triggers, FTS, defaults and existing project history.
const migrations = new URL("../../../infra/migrations/sqlite/", import.meta.url);
const output = new URL("../src/drizzle-schema.ts", import.meta.url);
const db = new DatabaseSync(":memory:");
try {
  db.exec("PRAGMA foreign_keys = OFF");
  for (const name of readdirSync(migrations).filter(name => /^\d+_.+\.sql$/.test(name)).sort()) {
    db.exec(readFileSync(new URL(name, migrations), "utf8"));
  }
  const tableNames = db.prepare("PRAGMA table_list").all()
    .filter(row => row.schema === "main" && row.type === "table" && !row.name.startsWith("sqlite_"))
    .map(row => row.name).sort();
  const lines = [
    "// Generated by pnpm --filter @munhae/db-sqlite generate:schema. Do not edit.",
    "// Query mappings only. SQL migrations own the physical schema; do not use schema push.",
    'import { sql } from "drizzle-orm";',
    'import { blob, integer, real, sqliteTable, text } from "drizzle-orm/sqlite-core";',
    "",
  ];
  for (const name of tableNames) {
    const ddl = db.prepare("SELECT sql FROM sqlite_schema WHERE name = ?").get(name).sql;
    const columns = db.prepare("SELECT * FROM pragma_table_info(?)").all(name);
    const singlePrimaryKey = columns.filter(column => column.pk).length === 1;
    lines.push(`const ${name} = sqliteTable(${JSON.stringify(name)}, {`);
    for (const column of columns) {
      const type = column.type.toUpperCase();
      const builder = { TEXT: "text", INTEGER: "integer", REAL: "real", BLOB: "blob" }[type];
      if (!builder) throw new Error(`Unsupported SQLite column: ${name}.${column.name} (${type})`);
      const check = ddl.match(new RegExp(`CHECK\\s*\\(\\s*"?${column.name}"?\\s+IN\\s*\\(([^)]+)\\)`, "i"));
      const enumValues = check && [...check[1].matchAll(/'((?:[^']|'')*)'/g)].map(match => match[1].replaceAll("''", "'"));
      const options = builder === "text" && enumValues?.length ? `, { enum: ${JSON.stringify(enumValues)} }` : "";
      let expression = `${builder}(${JSON.stringify(column.name)}${options})`;
      if (column.pk && singlePrimaryKey) expression += ".primaryKey()";
      if (column.notnull || (column.pk && type !== "INTEGER")) expression += ".notNull()";
      if (column.dflt_value !== null) expression += `.default(sql.raw(${JSON.stringify(column.dflt_value)}))`;
      lines.push(`  ${column.name}: ${expression},`);
    }
    lines.push("});", "");
  }
  lines.push("export const schema = {", ...tableNames.map(name => `  ${name},`), "};", "");
  const generated = lines.join("\n");
  if (process.argv.includes("--check")) {
    if (readFileSync(output, "utf8") !== generated) throw new Error("Drizzle schema is stale. Run pnpm --filter @munhae/db-sqlite generate:schema.");
    console.log(`Drizzle schema matches ${tableNames.length} migrated tables.`);
  } else {
    writeFileSync(output, generated);
    console.log(`Generated ${tableNames.length} tables in ${fileURLToPath(output)}.`);
  }
} finally {
  db.close();
}
