// Restrict every nested trigger query to the same online tenant. This also covers
// unscoped local tables such as actors, policy versions and translation layouts.
function scopedQueries(condition) {
 return expression(condition.replace(/\b(FROM|JOIN)\s+([a-z_]+)(?:\s+([a-z_]+))?/gi,(full,join,name,alias)=>{
  if(!names.has(name))throw new Error('Unknown trigger table '+name);
  const reserved=new Set(['where','join','on','and','or','order','group','limit','left','inner','right']);
  const tail=alias&&reserved.has(alias.toLowerCase())?' '+alias:'';
  const binding=alias&&!tail?alias:name;
  return `${join} (select * from ${sqlName(name)} where online_project_id=coalesce(NEW.online_project_id,OLD.online_project_id)) ${binding}${tail}`;
 }));
}
